def piecewise_quadrature(breaks, order):
    """Gauss-Legendre nodes on each polynomial piece."""
    nodes, weights = leggauss(order)
    breaks = np.asarray(breaks)
    half = 0.5 * np.diff(breaks)
    mid = 0.5 * (breaks[1:] + breaks[:-1])
    return (mid[:, None] + half[:, None] * nodes).ravel(), (half[:, None] * weights).ravel()


class DesignProblem:
    """Even cubic basis, exact local quadratic forms, and Fourier objective."""

    def __init__(self, theta_count=128, alias_half_width=8, fourier_order=16,
                 gram_theta_count=513):
        self.degree = 3
        self.breaks = np.linspace(-4.0, 4.0, 33)
        self.knots = np.r_[np.repeat(-4.0, 3), self.breaks, np.repeat(4.0, 3)]
        count = len(self.knots) - self.degree - 1
        groups = [(j, count - 1 - j) for j in range(2, (count + 1) // 2)]
        self.mapping = np.zeros((count, len(groups)))
        for column, pair in enumerate(groups):
            self.mapping[list(set(pair)), column] = 1.0
        self.basis = BSpline(self.knots, self.mapping, self.degree, extrapolate=False)
        self.dimension = self.mapping.shape[1]
        x, weights = piecewise_quadrature(self.breaks, 8)
        basis = self.basis(x)
        derivative = self.basis.derivative()(x)
        self.mass = basis.T @ weights
        self.energy = basis.T @ (weights[:, None] * basis)
        self.roughness = derivative.T @ (weights[:, None] * derivative)
        correlations = []
        for shift in range(8):
            translated = np.nan_to_num(self.basis(x - shift), nan=0.0)
            matrix = basis.T @ (weights[:, None] * translated)
            correlations.append(0.5 * (matrix + matrix.T))
        self.correlations = np.asarray(correlations)
        self.gram_theta = np.linspace(0.0, np.pi, gram_theta_count)
        self.gram_forms = self.gram_matrices(self.gram_theta)
        ratio = DECLARATION["gram_lower_ratio"] + DECLARATION["gram_numerical_margin"]
        self.constraint_forms = self.gram_forms - ratio * self.energy
        self.theta = (np.arange(theta_count) + 0.5) * np.pi / theta_count
        self.aliases = np.arange(-alias_half_width, alias_half_width + 1)
        omega = self.theta[:, None] + 2.0 * np.pi * self.aliases[None, :]
        qx, qw = piecewise_quadrature(self.breaks, fourier_order)
        flat = omega.ravel()
        fourier = np.empty((flat.size, self.dimension))
        weighted_basis = qw[:, None] * self.basis(qx)
        for first in range(0, flat.size, 512):
            fourier[first:first + 512] = np.cos(flat[first:first + 512, None] * qx) @ weighted_basis
        self.fourier = fourier.reshape(*omega.shape, self.dimension)
        self.integrated_fourier = self.fourier / omega[:, :, None]
        prior = (1.0 + (self.theta / 0.5)**2)**-2
        self.prior = prior / prior.sum()
        self.noncentral = self.aliases != 0

    def gram_matrices(self, theta):
        harmonics = np.cos(np.asarray(theta)[:, None] * np.arange(8)[None, :])
        harmonics[:, 1:] *= 2.0
        return np.einsum("tj,jab->tab", harmonics, self.correlations)

    def projection_error(self, a):
        amplitudes = self.integrated_fourier @ a
        squared = amplitudes**2
        denominator = squared.sum(axis=1)
        numerator = squared[:, self.noncentral].sum(axis=1)
        return numerator / denominator

    def objective_gradient(self, a):
        amplitudes = self.integrated_fourier @ a
        squared = amplitudes**2
        denominator = squared.sum(axis=1)
        numerator = squared[:, self.noncentral].sum(axis=1)
        dden = 2.0 * np.einsum("tk,tka->ta", amplitudes, self.integrated_fourier)
        dnum = 2.0 * np.einsum("tk,tka->ta", amplitudes[:, self.noncentral],
                              self.integrated_fourier[:, self.noncentral, :])
        error = numerator / denominator
        gradient = self.prior @ ((dnum - error[:, None] * dden) / denominator[:, None])
        regularizer = DECLARATION["tau"] * (a @ self.roughness @ a)
        gradient += 2.0 * DECLARATION["tau"] * (self.roughness @ a)
        return float(self.prior @ error + regularizer), gradient

    def constraint(self, a):
        return np.einsum("a,tab,b->t", a, self.constraint_forms, a)

    def constraint_jacobian(self, a):
        return 2.0 * np.einsum("tab,b->ta", self.constraint_forms, a)

    def gram_extrema(self, a):
        """Find all extrema of the finite trigonometric Gram polynomial."""
        coefficients = np.einsum("a,jab,b->j", a, self.correlations, a)
        coefficients[1:] *= 2.0
        polynomial = Chebyshev(coefficients)
        roots = polynomial.deriv().roots()
        real_roots = roots[np.abs(roots.imag) < 1e-9].real
        points = np.r_[-1.0, real_roots[(real_roots >= -1) & (real_roots <= 1)], 1.0]
        values = polynomial(points)
        low, high = np.argmin(values), np.argmax(values)
        energy = float(a @ self.energy @ a)
        return {"minimum": float(values[low]), "maximum": float(values[high]),
                "minimum_theta": float(np.arccos(points[low])),
                "maximum_theta": float(np.arccos(points[high])),
                "minimum_over_energy": float(values[low] / energy),
                "maximum_over_energy": float(values[high] / energy),
                "condition_ratio": float(values[high] / values[low])}

    def summary(self, a):
        objective, _ = self.objective_gradient(a)
        return {"objective": objective, "weighted_projection_error": float(self.prior @ self.projection_error(a)),
                "roughness": float(a @ self.roughness @ a),
                "roughness_penalty": float(DECLARATION["tau"] * (a @ self.roughness @ a)),
                "mass": float(self.mass @ a), "kernel_energy": float(a @ self.energy @ a),
                "gram": self.gram_extrema(a)}

    def design(self, a):
        return {"degree": self.degree, "knots": self.knots.tolist(),
                "coefficients": (self.mapping @ a).tolist(), "support": [-4.0, 4.0]}

    def starts(self):
        # Greville abscissae characterize each free symmetric coefficient pair.
        greville = np.array([self.knots[j + 1:j + 4].mean() for j in range(self.mapping.shape[0])])
        locations = np.array([abs(greville[np.flatnonzero(self.mapping[:, j])[0]])
                              for j in range(self.dimension)])
        profiles = {
            "narrow_gaussian": np.exp(-0.5 * (locations / 0.55)**2),
            "windowed_sinc": np.sinc(locations) * np.cos(np.pi * locations / 8.0)**2,
            "smooth_broad": np.maximum(1.0 - (locations / 4.0)**2, 0.0)**3,
        }
        return {name: values * (2.0 / (self.mass @ values)) for name, values in profiles.items()}


def audit_scaled_gram(design, scale=1.0, theta_count=4097, quadrature_order=8):
    """Audit translates of scale*K(scale*x); split at both shifted knot sets."""
    if scale <= 0.0:
        raise ValueError("scale must be positive")
    activation = LocalActivation(design)
    breaks = np.unique(design["knots"])
    radius = float(design["support"][1])
    correlations = []
    for shift in range(int(np.ceil(2.0 * radius / scale))):
        offset = scale * shift
        left, right = -radius + offset, radius
        pieces = np.unique(np.r_[left, breaks[(breaks > left) & (breaks < right)],
                                  (breaks + offset)[((breaks + offset) > left) & ((breaks + offset) < right)], right])
        x, weights = piecewise_quadrature(pieces, quadrature_order)
        correlations.append(float(scale * np.sum(weights * activation.derivative_numpy(x)
                                                * activation.derivative_numpy(x - offset))))
    theta = np.linspace(0.0, np.pi, theta_count)
    coefficients = np.asarray(correlations)
    coefficients[1:] *= 2.0
    values = np.cos(theta[:, None] * np.arange(len(coefficients))) @ coefficients
    polynomial = Chebyshev(coefficients)
    roots = polynomial.deriv().roots()
    real_roots = roots[np.abs(roots.imag) < 1e-8].real
    points = np.r_[-1.0, real_roots[(real_roots >= -1.0) & (real_roots <= 1.0)], 1.0]
    stationary_values = polynomial(points)
    # The dense grid is an independent numerical backstop for polynomial roots.
    minimum = min(float(stationary_values.min()), float(values.min()))
    maximum = max(float(stationary_values.max()), float(values.max()))
    return {"scale": float(scale), "kernel_energy": float(correlations[0]),
            "minimum": minimum, "maximum": maximum,
            "minimum_over_energy": minimum / correlations[0],
            "maximum_over_energy": maximum / correlations[0],
            "sampled_minimum": float(values.min()), "sampled_maximum": float(values.max()),
            "stationary_minimum": float(stationary_values.min()),
            "stationary_maximum": float(stationary_values.max()),
            "certificate": "Chebyshev derivative roots in [-1,1] plus endpoints, with dense-grid backstop; float64",
            "correlation_coefficients": correlations, "polynomial_degree": len(coefficients) - 1,
            "theta_count": theta_count, "quadrature_order": quadrature_order}


def _save(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(data, indent=2, allow_nan=False) + "\n")
    temporary.replace(path)


def solve(out=DEFAULT_OUT):
    """Run the predeclared three starts, validate, and freeze one local solution."""
    started = time.perf_counter()
    _save(out, {"complete": False, "declaration": DECLARATION, "status": "optimization in progress"})
    problem = DesignProblem()
    outcomes = []
    for name, initial in problem.starts().items():
        forms = problem.constraint_forms.copy()
        current = initial.copy()
        passes = []
        for refinement in range(6):
            history = []
            result = optimize.minimize(
                problem.objective_gradient, current, jac=True, method="SLSQP",
                constraints=[{"type": "eq", "fun": lambda a: problem.mass @ a - 2.0,
                              "jac": lambda a: problem.mass},
                             {"type": "ineq", "fun": lambda a: np.einsum("a,tab,b->t", a, forms, a),
                              "jac": lambda a: 2.0 * np.einsum("tab,b->ta", forms, a)}],
                callback=lambda a: history.append(float(problem.objective_gradient(a)[0])),
                options={"maxiter": DECLARATION["max_iterations"], "ftol": DECLARATION["ftol"], "disp": False},
            )
            summary = problem.summary(result.x)
            feasible = abs(summary["mass"] - 2.0) < 1e-8 and summary["gram"]["minimum_over_energy"] >= DECLARATION["gram_lower_ratio"] - 1e-8
            passes.append({"refinement": refinement, "success": bool(result.success), "feasible": bool(feasible),
                           "status": int(result.status), "message": str(result.message),
                           "iterations": int(result.nit), "function_evaluations": int(result.nfev),
                           "starting_free_coefficients": current.tolist(), "free_coefficients": result.x.tolist(),
                           "summary": summary, "objective_history": history})
            if feasible or not result.success:
                break
            extra = problem.gram_matrices([summary["gram"]["minimum_theta"]])
            extra -= (DECLARATION["gram_lower_ratio"] + DECLARATION["gram_numerical_margin"]) * problem.energy
            forms = np.concatenate([forms, extra])
            current = result.x.copy()
        outcome = {"start": name, "success": bool(result.success), "feasible": bool(feasible),
                   "status": int(result.status), "message": str(result.message),
                   "iterations": int(result.nit), "function_evaluations": int(result.nfev),
                   "initial_free_coefficients": initial.tolist(), "free_coefficients": result.x.tolist(),
                   "initial": problem.summary(initial), "final": summary,
                   "objective_history": history, "optimization_passes": passes}
        outcomes.append(outcome)
        print(f"{name}: success={result.success} feasible={feasible} objective={summary['objective']:.9g} "
              f"gram_min/energy={summary['gram']['minimum_over_energy']:.8g} iterations={result.nit}", flush=True)
    eligible = [row for row in outcomes if row["success"] and row["feasible"]]
    if not eligible:
        _save(out, {"complete": False, "declaration": DECLARATION, "optimizer_outcomes": outcomes})
        raise RuntimeError("No converged feasible local design; all outcomes saved")
    selected = min(eligible, key=lambda row: row["final"]["objective"])
    coefficients = np.asarray(selected["free_coefficients"])
    refined_problem = DesignProblem(theta_count=512, alias_half_width=16, fourier_order=24)
    starting_refined = refined_problem.summary(coefficients)
    refinement_passes = []
    forms = refined_problem.constraint_forms.copy()
    current = coefficients.copy()
    def refined_objective(a):
        value, gradient = refined_problem.objective_gradient(a)
        multiplier = DECLARATION["resolution_refinement"]["objective_multiplier_for_solver"]
        return multiplier * value, multiplier * gradient
    for refinement in range(6):
        history = []
        refined = optimize.minimize(
            refined_objective, current, jac=True, method="SLSQP",
            constraints=[{"type": "eq", "fun": lambda a: refined_problem.mass @ a - 2.0,
                          "jac": lambda a: refined_problem.mass},
                         {"type": "ineq", "fun": lambda a: np.einsum("a,tab,b->t", a, forms, a),
                          "jac": lambda a: 2.0 * np.einsum("tab,b->ta", forms, a)}],
            callback=lambda a: history.append(float(refined_problem.objective_gradient(a)[0])),
            options={"maxiter": DECLARATION["max_iterations"],
                     "ftol": DECLARATION["resolution_refinement"]["solver_ftol"], "disp": False},
        )
        refined_summary = refined_problem.summary(refined.x)
        feasible = abs(refined_summary["mass"] - 2.0) < 1e-8 and refined_summary["gram"]["minimum_over_energy"] >= DECLARATION["gram_lower_ratio"] - 1e-8
        refinement_passes.append({"refinement": refinement, "success": bool(refined.success), "feasible": bool(feasible),
                                  "status": int(refined.status), "message": str(refined.message),
                                  "iterations": int(refined.nit), "function_evaluations": int(refined.nfev),
                                  "starting_free_coefficients": current.tolist(), "free_coefficients": refined.x.tolist(),
                                  "summary": refined_summary, "objective_history": history})
        if feasible or not refined.success:
            break
        extra = refined_problem.gram_matrices([refined_summary["gram"]["minimum_theta"]])
        extra -= (DECLARATION["gram_lower_ratio"] + DECLARATION["gram_numerical_margin"]) * refined_problem.energy
        forms = np.concatenate([forms, extra])
        current = refined.x.copy()
    resolution_refinement = {"initial": starting_refined, "final": refined_summary,
                             "optimization_passes": refinement_passes,
                             "coefficient_change_norm": float(np.linalg.norm(refined.x - coefficients))}
    if not (refined.success and feasible):
        _save(out, {"complete": False, "declaration": DECLARATION, "optimizer_outcomes": outcomes,
                    "resolution_refinement": resolution_refinement})
        raise RuntimeError("Numerical-resolution refinement did not converge feasibly")
    coefficients = refined.x
    print(f"theta512 refinement: objective {starting_refined['objective']:.9g} -> {refined_summary['objective']:.9g}; "
          f"gram_min/energy={refined_summary['gram']['minimum_over_energy']:.8g}", flush=True)
    design = problem.design(coefficients)
    validation = []
    for order in DECLARATION["validation_fourier_quadrature_orders"]:
        dense = DesignProblem(theta_count=DECLARATION["validation_theta_count"],
                              alias_half_width=DECLARATION["validation_alias_half_width"],
                              fourier_order=order, gram_theta_count=DECLARATION["validation_gram_theta_count"])
        validation.append({"fourier_quadrature_order": order, **dense.summary(coefficients)})
    tail_validation = []
    for order in DECLARATION["tail_validation_quadrature_orders"]:
        wider = DesignProblem(theta_count=DECLARATION["tail_validation_theta_count"],
                              alias_half_width=DECLARATION["tail_validation_alias_half_width"],
                              fourier_order=order, gram_theta_count=DECLARATION["validation_gram_theta_count"])
        tail_validation.append({"fourier_quadrature_order": order, **wider.summary(coefficients)})
    tail_reference = DesignProblem(theta_count=DECLARATION["tail_validation_theta_count"],
                                   alias_half_width=16, fourier_order=32, gram_theta_count=3).summary(coefficients)
    theta_convergence = []
    for theta_count in DECLARATION["theta_convergence_counts"]:
        finer = DesignProblem(theta_count=theta_count, alias_half_width=16,
                              fourier_order=32, gram_theta_count=3)
        theta_convergence.append({"theta_count": theta_count, **finer.summary(coefficients)})
    record = {**design, "complete": True, "declaration": DECLARATION,
              "free_coefficients": coefficients.tolist(), "free_parameter_count": problem.dimension,
              "independent_parameter_count_after_mass": problem.dimension - 1,
              "smoothness": "K globally C1 and piecewise cubic (C2 at interior knots); activation globally C2",
              "selected_start": selected["start"], "selection": "lowest initial-grid objective among converged feasible starts, then numerical-resolution refinement of the same functional",
              "selected": refined_summary, "initial_selected": selected["final"],
              "optimizer_outcomes": outcomes, "resolution_refinement": resolution_refinement,
              "validation": {"theta_1024_alias_16": validation,
                             "alias_64": tail_validation,
                             "tail_reference_theta_256_alias_16": tail_reference,
                             "theta_convergence_alias_16_order_32": theta_convergence,
                             "dense_gram": audit_scaled_gram(design),
                             "quadrature_objective_difference": abs(validation[1]["objective"] - validation[0]["objective"]),
                             "tail_quadrature_objective_difference": abs(tail_validation[1]["objective"] - tail_validation[0]["objective"]),
                             "alias_16_to_64_objective_difference": tail_validation[1]["objective"] - tail_reference["objective"],
                             "discretization_objective_difference": abs(validation[1]["objective"] - refined_summary["objective"])},
              "wall_seconds": time.perf_counter() - started}
    if record["validation"]["dense_gram"]["minimum_over_energy"] < DECLARATION["gram_lower_ratio"] - 1e-8:
        record["complete"] = False
        record["failure"] = "Dense/continuous Gram validation failed"
        _save(out, record)
        raise RuntimeError("Dense Gram validation failed")
    _save(out, record)
    plot_diagnostics(refined_problem, record, Path(out).parent)
    return record


def plot_diagnostics(problem, design, directory):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    x = np.linspace(-4.5, 4.5, 2001)
    theta = np.linspace(0.0, np.pi, 1201)
    gram = problem.gram_matrices(theta)
    fig, axes = plt.subplots(2, 2, figsize=(11, 8))
    curves = [(row["start"].replace("_", " "), np.asarray(row["initial_free_coefficients"]), False)
              for row in design["optimizer_outcomes"]]
    curves.append(("selected local solution", np.asarray(design["free_coefficients"]), True))
    for label, coefficients, selected in curves:
        activation = LocalActivation(problem.design(coefficients))
        style = {"linewidth": 2.4 if selected else 1.2, "alpha": 1.0 if selected else 0.65,
                 "color": "black" if selected else None, "label": label}
        axes[0, 0].plot(x, activation.derivative_numpy(x), **style)
        axes[0, 1].plot(x, activation.numpy(x), **style)
        axes[1, 0].semilogy(problem.theta, np.maximum(problem.projection_error(coefficients), 1e-17), **style)
        values = np.einsum("a,tab,b->t", coefficients, gram, coefficients) / (coefficients @ problem.energy @ coefficients)
        axes[1, 1].plot(theta, values, **style)
    axes[0, 0].set(title="Compact derivative kernel K", xlabel="z", ylabel="K(z)")
    axes[0, 1].set(title="Integrated activation", xlabel="z", ylabel="sigma(z)")
    axes[1, 0].set(title="Pure-tone alias projection error", xlabel="theta (radians)", ylabel="relative squared error")
    axes[1, 1].axhline(DECLARATION["gram_lower_ratio"], color="firebrick", linestyle="--", linewidth=1, label="required lower ratio")
    axes[1, 1].set(title="Derivative translate Gram at unit spacing", xlabel="theta (radians)", ylabel="g(theta) / integral K²")
    for axis in axes.flat:
        axis.grid(alpha=0.2)
    handles, labels = axes[0, 0].get_legend_handles_labels()
    threshold_handles, threshold_labels = axes[1, 1].get_legend_handles_labels()
    fig.legend(handles + threshold_handles[-1:], labels + threshold_labels[-1:],
               loc="lower center", bbox_to_anchor=(0.5, -0.035), ncol=3, fontsize=8, frameon=False)
    fig.suptitle("Target-independent compact spline design: three starts and one local constrained solution")
    fig.tight_layout()
    for suffix in ("png", "pdf"):
        fig.savefig(Path(directory) / f"design_diagnostics.{suffix}", dpi=180, bbox_inches="tight")
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    result = solve(args.out)
    print(f"Frozen {args.out}: selected {result['selected_start']}; objective={result['selected']['objective']:.9g}", flush=True)


if __name__ == "__main__":
    main()
